#include <stdio.h>
#include <stdlib.h>


int main(int argc, char *argv[]) {
	float a,b,c;
    a = 10;
    b = 6;
    c = a + b;
    printf("A soma de %f + %f = %f\n", a,b,c);
    c = a - b;
    printf("A subtracao de %f - %f = %f\n", a,b,c);
    c = a * b;
    printf("A multiplicacao de %f * %f = %f\n", a,b,c);
    c = a / b;
    printf("A divisao de %f / %f = %f\n", a,b,c);
	return 0;
}







